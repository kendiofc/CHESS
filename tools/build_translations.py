#!/usr/bin/env python3
"""Build the client's translation tables from tools/translations.txt.

translations.txt holds one block per English text:

    = Best run: %d
    es: Mejor partida: %d
    pt: Melhor partida: %d
    ...

The English line is exactly what the UI code writes (including format
specifiers such as %d / %s, which the translation must keep, in the same
order, or name with {1}, {2}... to reorder). Lines starting with # are
comments. Writes src/client/UI/Translations/<code>.luau for each language.

Usage: python3 tools/build_translations.py [--check]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "translations.txt"
OUT = ROOT / "src" / "client" / "UI" / "Translations"
LANGUAGES = ["es", "pt", "fr", "de", "id"]
SPEC = re.compile(r"%\d*[ds]")


def parse():
    entries = {}
    order = []
    current = None
    for number, raw in enumerate(SOURCE.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        if line.startswith("= "):
            current = line[2:]
            if current in entries:
                raise SystemExit(f"line {number}: duplicate entry {current!r}")
            entries[current] = {}
            order.append(current)
        else:
            match = re.match(r"^([a-z]{2}): (.*)$", line)
            if not match or current is None:
                raise SystemExit(f"line {number}: can't read {line!r}")
            code, text = match.groups()
            if code not in LANGUAGES:
                raise SystemExit(f"line {number}: unknown language {code}")
            entries[current][code] = text
    return entries, order


def check(entries):
    problems = []
    for source, out in entries.items():
        missing = [code for code in LANGUAGES if code not in out]
        if missing:
            problems.append(f"{source!r}: missing {', '.join(missing)}")
        wanted = SPEC.findall(source)
        for code, text in out.items():
            numbered = re.findall(r"\{(\d)\}", text)
            if numbered:
                if sorted(int(n) for n in numbered) != list(range(1, len(wanted) + 1)):
                    problems.append(f"{source!r} [{code}]: placeholders {numbered} for {len(wanted)} values")
            elif [s[-1] for s in SPEC.findall(text)] != [s[-1] for s in wanted]:
                problems.append(f"{source!r} [{code}]: format {SPEC.findall(text)} should be {wanted}")
    return problems


def luau_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    entries, order = parse()
    problems = check(entries)
    for problem in problems:
        print(problem)
    if problems:
        return 1
    if "--check" in sys.argv:
        print(f"{len(entries)} texts, {len(LANGUAGES)} languages: ok")
        return 0
    OUT.mkdir(exist_ok=True)
    for code in LANGUAGES:
        lines = [
            "--!strict",
            f"-- Generated by tools/build_translations.py from tools/translations.txt ({code}).",
            "-- Edit translations.txt, not this file.",
            "return {",
        ]
        for source in order:
            lines.append(f"\t[{luau_string(source)}] = {luau_string(entries[source][code])},")
        lines.append("}")
        (OUT / f"{code}.luau").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(LANGUAGES)} tables, {len(entries)} texts each")
    return 0


if __name__ == "__main__":
    sys.exit(main())
